"""Merge the content batches (content/gospels-*.json, then content/acts-*.json, then content/beyond-*.json, plus content/today.json) into js/content.js.

Run from the repo root after copying new batch files into content/ and their images into img/:
    python3 tools/build_content.py && python3 tools/routestats.py
Places already defined in js/data.js are kept as they are; only new place ids are added.
"""
import json, glob, re

data = open('js/data.js').read()
known = set(re.findall(r'^  (\w+):\s+\{ name:', data, re.M))
places, events, ids = {}, [], set()
for f in sorted(glob.glob('content/gospels-*.json')) + sorted(glob.glob('content/acts-*.json')) + sorted(glob.glob('content/beyond-*.json')):
    d = json.load(open(f))
    for k, p in d['places'].items():
        if k not in known and k not in places:
            places[k] = p
    for e in d['events']:
        assert e['id'] not in ids, e['id']
        ids.add(e['id'])
        events.append(e)
# Present-day photos and notes for places (content/today.json); data.js places keep their own
try:
    for k, t in json.load(open('content/today.json')).items():
        if k in places and 'today' not in places[k]:
            places[k]['today'] = t
except FileNotFoundError:
    pass
for e in events:
    for k in ('place', 'from'):
        if e.get(k):
            assert e[k] in places or e[k] in known, (e['id'], e[k])

dump = lambda o: json.dumps(o, ensure_ascii=False, separators=(',', ':'))
with open('js/content.js', 'w') as out:
    out.write('// Generated by tools/build_content.py from content/*.json. Do not edit by hand.\n')
    out.write('// The Gospel events after the Baptism, in the order of A. T. Robertson\'s Harmony of the Gospels (1922), then the Acts of the Apostles, then the apostles after Acts by tradition.\n')
    out.write('const CONTENT_PLACES = {\n' + ',\n'.join(f'  {json.dumps(k)}: {dump(v)}' for k, v in places.items()) + '\n};\n')
    out.write('const CONTENT_EVENTS = [\n' + ',\n'.join('  ' + dump(e) for e in events) + '\n];\n')
    # Daily-life explainers (content/explainers.json), each linked from the events it lists
    ex = {k: v for k, v in json.load(open('content/explainers.json')).items() if not k.startswith('_')}
    for k, v in ex.items():
        for i in v['events']:
            assert i in ids or re.search(r'id: "%s"' % i, data), (k, i)
    out.write('const CONTENT_EXPLAINERS = ' + json.dumps(ex, ensure_ascii=False, indent=1) + ';\n')
print(len(places), 'new places,', len(events), 'events')
